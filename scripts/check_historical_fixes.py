def grep(pattern: str, path: str) -> bool:
    """rg if available, else grep -r. Exit 0 = match found."""
    try:
        r = subprocess.run(
            ["rg", "--quiet", "-U", pattern, path],
            capture_output=True, timeout=20,
        )
        return r.returncode == 0
    except FileNotFoundError:
        r = subprocess.run(
            ["grep", "-rqE", pattern, path],
            capture_output=True, timeout=20,
        )
        return r.returncode == 0


